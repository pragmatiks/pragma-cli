#!/usr/bin/env bash
set -euo pipefail

hooks_directory=$(git rev-parse --path-format=absolute --git-path hooks)
expected_hooks_directory="$(git rev-parse --path-format=absolute --git-common-dir)/hooks"
hook_template=scripts/git_hooks/hook.sh

if [ "$hooks_directory" != "$expected_hooks_directory" ]; then
  echo "Git reads hooks from $hooks_directory (core.hooksPath), but the hooks install into $expected_hooks_directory." >&2
  echo "Point core.hooksPath at $expected_hooks_directory or unset it." >&2
  exit 1
fi

mkdir -p "$expected_hooks_directory"

for hook_type in $(yq -r '.default_install_hook_types[]' .pre-commit-config.yaml); do
  hook_path="$expected_hooks_directory/$hook_type"

  if [ -f "$hook_path" ] && cmp -s "$hook_template" "$hook_path"; then
    continue
  fi

  if [ -e "$hook_path" ] && ! grep -qxE '# pragmatiks-git-hook|# File generated by pre-commit: .*' "$hook_path"; then
    echo "$hook_path is not a Pragmatiks or pre-commit hook; move it away, then run \`mise run install:hooks\` again." >&2
    exit 1
  fi

  if [ -e "$hook_path.legacy" ]; then
    echo "$hook_path.legacy is a hook pre-commit chained to, which the installed hook does not run; merge it into .pre-commit-config.yaml or remove it, then run \`mise run install:hooks\` again." >&2
    exit 1
  fi

  install -m 0755 "$hook_template" "$hook_path"
  echo "Installed the $hook_type hook at $hook_path"
done
